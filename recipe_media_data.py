def get_recipe_info(slug, title, main_ing, cat_slug):
    """
    Retorna a foto gastronômica real e a descrição apetitosa de cada receita com garantia semântica.
    """
    if slug in RECIPE_SPECIFIC_DATA:
        return RECIPE_SPECIFIC_DATA[slug]["img"], RECIPE_SPECIFIC_DATA[slug]["desc"]
    
    t_lower = (title + " " + slug).lower()
    desc = f"Aprenda como preparar {title} passo a passo com checklist, timers e segredos de ponto."
    
    # 1. Regras para Boteco
    if cat_slug == "boteco":
        if any(k in t_lower for k in ["torresmo", "panceta", "pururuca", "courinho"]):
            return "/assets/recipes/boteco/torresmo-rolo.jpg", f"Torresmo pururucado com casquinha crocante e carne suculenta. {desc}"
        elif any(k in t_lower for k in ["tapioca", "dadinho"]):
            return "/assets/recipes/boteco/dadinho-tapioca.jpg", f"Dadinhos de tapioca dourados e crocantes servidos com geleia de pimenta. {desc}"
        elif any(k in t_lower for k in ["feijoada"]):
            return "/assets/recipes/boteco/bolinho-feijoada.jpg", f"Bolinho de feijoada crocante recheado com couve fininha e bacon. {desc}"
        elif any(k in t_lower for k in ["mandioca", "aipim", "macaxeira"]):
            return "/assets/recipes/boteco/mandioca-frita.jpg", f"Mandioca frita sequinha por fora e muito macia por dentro. {desc}"
        elif any(k in t_lower for k in ["calabresa", "chourico", "chouriço", "linguica", "linguiça"]):
            return "/assets/recipes/boteco/calabresa-acebolada.jpg", f"Calabresa acebolada na cachaça dourada na chapa de boteco. {desc}"
        elif any(k in t_lower for k in ["peixe", "tilapia", "tilápia", "isca", "camarao", "camarão"]):
            return "/assets/recipes/boteco/isca-tilapia.jpg", f"Iscas de peixe crocantes empanadas no fubá com molho tártaro. {desc}"
        elif any(k in t_lower for k in ["coxinha", "croquete", "frango"]):
            return "/assets/recipes/boteco/coxinha-frango.jpg", f"Petisco crocante e sequinho dourado na hora para acompanhar aquela cerveja gelada. {desc}"
        elif any(k in t_lower for k in ["pastel", "pasteizinhos"]):
            return "/assets/recipes/pastel.jpg", f"Pastel crocante com massa sequinha e recheio generoso. {desc}"
